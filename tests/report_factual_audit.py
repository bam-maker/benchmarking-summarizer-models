def report():
    manifest = verify()
    rows = [
        read(WORK / "controls" / f"{number:03d}_{model}.json")
        for number in ROWS
        for model in MODELS
    ]
    chunks = [c for r in rows for c in r["chunk_controls"]]
    probes = [v for c in chunks for v in c["variants"].values()] + [
        v for r in rows for v in r["prefix_diagnostics"]
    ]
    old = read(ROOT / "reports/validation_40_results.json")
    result = {
        "kind": "Frozen factual-error controlled audit; no human ratings or causal proof beyond the specified interventions",
        "protocol": "factual_audit_manifest.json",
        "automated_checks": {
            "case_model_pairs": len(rows),
            "direct_model_calls": len(probes),
            "replayed_source_chunks": len(chunks),
            "matching_raw_ids_chunks": sum(
                c["direct_same_settings_raw_ids_equal_application"] for c in chunks
            ),
            "matching_displayed_chunks": sum(
                c["direct_same_settings_display_equal_application"] for c in chunks
            ),
            "matching_merged_summaries": sum(
                r["direct_app_merge_equal_saved_application"] for r in rows
            ),
            "exact_source_reconstructions": sum(
                "".join(c["source_text"] for c in r["chunk_controls"])
                == r["source"]["article"]
                for r in rows
            ),
            "termination": dict(Counter(v["termination"] for v in probes)),
            "protected_evidence_unchanged": True,
            "note": "Equality, coverage and EOS are software observations, not factuality ratings.",
        },
        "ai_assisted_source_comparisons": OBSERVATIONS,
        "human_ratings_collected": False,
        "production_recommendation": "Retain current implementation/settings. No tested intervention consistently resolves the five failures. No candidate promoted; separate reserved validation42-47 was not run because there is no supported production-change proposal. Do not infer benefit from selective disappearance of one error.",
        "preprocessing_audit": {
            "documented": "Stanford CoreNLP3.7 PTBTokenizer with preserveLines, followed by lowercase; original script adds missing terminal periods by original story line, uses non-anonymized words, target sentence tags; pinned OpenNMT dynamic_dict/share_vocab and source400/target100 convention. Own checkpoint vocabularies and dynamic copy mapping retained in direct Translator.translate.",
            "observed_discrepancy": "NLTK approximation can retain terminal period on a word immediately before a quote (front., boost., together., discord.) and split abbreviations differently (p.m., Mo., Det.). Stanford tokens differ, and generation can change, but failure removal is not consistent.",
            "limits": manifest["tokenizer_limitations"],
            "historical_recipe_ambiguity": manifest["historical_ambiguity"],
            "differences": [],
        },
        "template_reference_audit": {
            "original_result_files_preserved": True,
            "identical_references": True,
            "contents": "Row10 (March10,2015) introduces international stories about a solar plane, Asian craters and Everest. Row14 (March9,2015) introduces Selma, MH370, International Women's Day and unemployment. Both then contain the same transcript-access/roll-call boilerplate. Their identical highlights emphasize transcript/roll-call instructions, not those different episode topics. Every model reproduces closely matching template text, including a reading-comprehension/vocabulary sentence not explicitly present in either article.",
            "interpretation": "Reference/template artifacts can reward generic language and ignore episode events. This does not prove memorization, training membership or validation leakage. No bad-performing example was excluded; the original40 remain primary and the existing38-page post-hoc sensitivity remains labeled.",
            "original_40_primary": {
                m: old["models"][m]["rouge_f1_mean_all_articles_percent"]
                for m in MODELS
            },
            "preserved_posthoc_38_non_template": old["reference_audit"][
                "non_template_rouge_f1_mean_percent"
            ],
            "original_results_sha256": manifest["preserved_sha256"][
                "reports/validation_40_results.json"
            ],
        },
        "cases": [],
    }
    for r in rows:
        case = {
            "row_idx": r["row_idx"],
            "label": r["label"],
            "model": r["model"],
            "article_id": r["source"]["id"],
            "article_sha256": r["source"]["article_sha256"],
            "raw_evidence": f"../test-results/factual_audit/controls/{r['row_idx']:03d}_{r['model']}.json",
            "application_summary": r["saved_application"]["summary"],
            "source_coverage_fraction": r["saved_application"][
                "input_presented_fraction"
            ],
            "source_chunks": r["saved_application"]["planned_chunks"],
            "consolidation_passes": r["saved_application"]["diagnostics"][
                "consolidation_passes"
            ],
            "chunk_controls": [],
            "prefix_diagnostics": [],
        }
        for c in r["chunk_controls"]:
            case["chunk_controls"].append(
                {
                    "chunk": c["chunk"],
                    "source_sha256": c["source_sha256"],
                    "direct_raw_matches_app": c[
                        "direct_same_settings_raw_ids_equal_application"
                    ],
                    "variants": {
                        key: {
                            k: v[k]
                            for k in (
                                "displayed_output",
                                "input_tokens",
                                "output_words",
                                "output_tokens",
                                "effective_settings",
                                "termination",
                                "generation_seconds",
                            )
                        }
                        for key, v in c["variants"].items()
                    },
                }
            )
            if "stanford_tokens" in c:
                a, b = c["app_approximation_tokens"], c["stanford_tokens"]
                changes = [
                    {"operation": tag, "app_tokens": a[x:y], "stanford_tokens": b[u:v]}
                    for tag, x, y, u, v in difflib.SequenceMatcher(
                        a=a, b=b, autojunk=False
                    ).get_opcodes()
                    if tag != "equal"
                ]
                result["preprocessing_audit"]["differences"].append(
                    {
                        "row_idx": r["row_idx"],
                        "model": r["model"],
                        "chunk": c["chunk"],
                        "changes": changes,
                    }
                )
        for p in r["prefix_diagnostics"]:
            case["prefix_diagnostics"].append(
                {
                    k: p[k]
                    for k in (
                        "preprocessing",
                        "window",
                        "complete_original_tokens",
                        "omitted_tokens",
                        "token_coverage_fraction",
                        "is_full_article",
                        "displayed_output",
                        "effective_settings",
                        "termination",
                    )
                }
            )
        result["cases"].append(case)
    save(ROOT / "reports/factual_audit_results.json", result)
    export(rows, result)
    verify()
    print(
        json.dumps(
            {
                "checks": result["automated_checks"],
                "recommendation": result["production_recommendation"],
            },
            indent=2,
        )
    )


def export(rows, result):
    with (ROOT / "reports/factual_audit_summary.csv").open(
        "w", encoding="utf-8-sig", newline=""
    ) as stream:
        writer = csv.DictWriter(stream, fieldnames=list(OBSERVATIONS[0]))
        writer.writeheader()
        writer.writerows(OBSERVATIONS)
    overview = "<h2>Five fixed failures: AI-assisted source comparison</h2><table><tr><th>Failure</th><th>Suspected cause</th><th>Controlled evidence</th><th>Proposed fix or limitation</th></tr>"
    for note in OBSERVATIONS:
        overview += (
            "<tr>"
            + "".join(
                "<td>" + html.escape(note[key]) + "</td>"
                for key in (
                    "failure",
                    "suspected_cause",
                    "controlled_evidence",
                    "proposed_fix_or_limitation",
                )
            )
            + "</tr>"
        )
    overview += "</table>"
    articles = []
    for number, label in ROWS.items():
        group = [r for r in rows if r["row_idx"] == number]
        source = group[0]["source"]
        block = f'<article id="row-{number}"><h2>{number}: {html.escape(label)} — {source["id"]}</h2><details><summary>Exact source</summary><pre>{html.escape(source["article"])}</pre></details><h3>Original reference</h3><pre>{html.escape(source["reference"])}</pre>'
        for r in group:
            block += f'<h3>{r["model"]}</h3><p><strong>Saved application output:</strong> {html.escape(r["saved_application"]["summary"])}</p><p>Full input coverage; {len(r["chunk_controls"])} chunk(s); direct app-setting raw IDs and merged display match. <a href="../test-results/factual_audit/controls/{number:03d}_{r["model"]}.json">Exact source, reference, raw/model input IDs, outputs and all settings (local JSON)</a>.</p><details><summary>Controlled per-chunk outputs and settings</summary>'
            for c in r["chunk_controls"]:
                block += f"<h4>Chunk {c['chunk'] + 1}</h4><details><summary>Exact source text for this chunk</summary><pre>{html.escape(c['source_text'])}</pre></details>"
                for key, v in c["variants"].items():
                    block += f"<section><strong>{key}</strong> — {v['input_tokens']} input tokens; {v['output_tokens']} output tokens; {v['termination']}<pre>{html.escape(v['displayed_output'])}</pre><details><summary>Effective decoding configuration</summary><pre>{html.escape(json.dumps(v['effective_settings'], indent=2))}</pre></details></section>"
            block += "</details>"
            if r["prefix_diagnostics"]:
                block += "<details><summary>400 versus 1024 source-token prefix diagnostics — partial unless explicitly complete</summary>"
                for p in r["prefix_diagnostics"]:
                    scope = (
                        "COMPLETE SOURCE fits"
                        if p["is_full_article"]
                        else "PARTIAL PREFIX — NOT a full-article summary"
                    )
                    block += f"<section><strong>{p['preprocessing']}, window {p['window']}: {scope}</strong><p>{p['input_tokens']}/{p['complete_original_tokens']} tokens presented; {p['omitted_tokens']} omitted. Fixed documented min35/max100.</p><pre>{html.escape(p['displayed_output'])}</pre></section>"
                block += "</details>"
        articles.append(block + "</article>")
    anomalies = (
        "<article><h2>Template/reference anomalies: retained in primary results</h2><p>"
        + html.escape(result["template_reference_audit"]["contents"])
        + "</p><p>"
        + html.escape(result["template_reference_audit"]["interpretation"])
        + "</p>"
    )
    for number in (10, 14):
        evidence = read(WORK / "sources" / f"{number:03d}.json")
        source = evidence["source"]
        anomalies += f"<h3>Row {number} — {source['id']}</h3><details><summary>Exact source and reference</summary><pre>{html.escape(source['article'])}</pre><h4>Original reference</h4><pre>{html.escape(source['reference'])}</pre></details>"
        for name, saved in evidence["application_saved"].items():
            anomalies += (
                f"<p><strong>{name}:</strong> {html.escape(saved['summary'])}</p>"
            )
    anomalies += '<p>Unchanged original scores and clearly labeled post-hoc sensitivity: <a href="validation_40_results.json">original validation results</a>. No new exclusions.</p></article>'
    page = (
        '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Controlled factual-error audit</title><style>body{font:16px/1.6 system-ui;max-width:1250px;margin:28px auto;padding:0 20px;color:#172c27}table{border-collapse:collapse;width:100%}td,th{padding:12px;border:1px solid #c4d1cb;text-align:left;vertical-align:top}article{margin:36px 0;padding:22px;border:1px solid #bdcdc4;border-radius:10px}section{padding:12px;margin:10px 0;background:#f3f6f4}pre{white-space:pre-wrap;overflow-wrap:anywhere;font:inherit}summary{cursor:pointer;margin:12px 0}h2,h3{overflow-wrap:anywhere}@media(max-width:650px){table{display:block;overflow:auto}td{min-width:180px}}</style><h1>Frozen factual-error causal audit</h1><p>Five fixed development cases; all four existing checkpoints; RTX4090 CUDA float32. 172 direct inference calls, 24 exact source chunks. Every direct app-setting raw output matches saved application IDs; all20 merged displays match. Original app, settings, validation reports and selected raw evidence are byte-for-byte unchanged.</p><p><strong>No human ratings collected.</strong> The judgments below are AI-assisted source/reference comparisons; equality, token coverage and EOS are automated checks and do not establish factual accuracy. No production change recommended or made. No candidate was promoted; separate candidate validation was therefore not run.</p><p>Each decoding edge changes one factor: HF defaults → forced EOS disabled → adaptive maximum → adaptive minimum; a separate minimum-only branch is saved. Legacy recipe35/100 → adaptive maximum → adaptive minimum; separate tokenizer swaps preserve source content and settings. Window diagnostics intentionally change available content and are explicitly partial. See the <a href="factual_audit_manifest.json">frozen protocol and tool provenance</a> and <a href="factual_audit_results.json">structured results</a>.</p><p>Original OpenNMT corpus used Stanford3.7 PTB tokenization then lowercasing, source400/target100 and target-only sentence tags. Original story line boundaries/period repairs cannot be fully recovered from flattened HF text. Pinned command uses beam5/alpha0.9; prose says0.8 and current website beam10. This audit uses the pinned explicit command, not a guessed universal default.</p>'
        + overview
        + "".join(articles)
        + anomalies
        + "</html>"
    )
    (ROOT / "reports/factual_audit_review.html").write_text(page, encoding="utf-8")


if __name__ == "__main__":
    report()
